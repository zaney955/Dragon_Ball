export function neutralMove(id, type, index) {
  const p = NEUTRAL_BALANCE[id];
  const [startup, active, recovery, dmg, stun, blockstun, guardDamage] = p[type][index];
  const last = index === p[type].length - 1;
  return {
    startup: startup / 60,
    active: active / 60,
    recovery: recovery / 60,
    dmg,
    stun: stun / 60,
    blockstun: blockstun / 60,
    guardDamage,
    confirmWindow: 0.1,
    blockCancelDelay: 0.1,
    linkWindow: type === 'light' ? 0.3 : 0.22,
    cancelRules: {
      hit: last
        ? ['special', 'ult', 'pursuit']
        : type === 'light'
          ? ['light', 'heavy', 'special', 'ult', 'dash', 'pursuit']
          : ['heavy', 'pursuit'],
      block: p.block[type]?.[index] ?? [],
      whiff: [],
    },
  };
}
